#!/bin/sh
# gunmetal-blue-accent-bundle.sh — rollback the Tiger experiment, then recolour
# ONLY the red accents of the current Quake-Gunmetal emerald + xfce themes to
# Prussian blue. Selections keep their black gradient. No white is added.
# Every modified tree is backed up first; rollback: gunmetal-blue-accent restore
set -e
BIN="$HOME/.local/bin"
mkdir -p "$BIN"
echo "== extracting tools to $BIN =="
sed -n '/^__BLUE_PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | tar -xzf - -C "$BIN"
chmod 755 "$BIN"/*
echo "== rolling back Tiger GTK theme (back to Quake-Gunmetal-3D) =="
"$BIN/tiger-gunmetal-gtk3-theme" restore || echo "  skipped (not applied or no xfconf)"
echo "== rolling back Tiger emerald deco (back to Quake-Gunmetal-Aqua) =="
"$BIN/tiger-gunmetal-emerald-theme" restore --baseline "$HOME/.emerald/themes/Quake-Gunmetal-Aqua" --no-restart || echo "  skipped (library theme absent)"
echo "== applying blue accent to the current themes =="
"$BIN/gunmetal-blue-accent" apply
echo "== restarting emerald to load the new pixmaps =="
if command -v emerald >/dev/null 2>&1; then (emerald --replace >/dev/null 2>&1 &); echo "  emerald --replace sent"; else echo "  emerald not found; restart it manually"; fi
echo "== status =="
"$BIN/gunmetal-blue-accent" status
echo "DONE. GTK apps pick the css up when restarted. Send photos of the bars/selections."
exit 0
