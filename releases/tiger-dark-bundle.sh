#!/bin/sh
# tiger-dark-bundle.sh (v3) — one file, three things:
#   1. context + red->Prussian-blue on your ACTIVE themes ONLY (xfconf-detected)
#   2. rebuild Tiger-Gunmetal v3: dark-grey highlights, mostly-black brushed body
#   3. restart emerald and show preview paths
# Blue-accent rollback: gunmetal-blue-accent restore
set -e
BIN="$HOME/.local/bin"
mkdir -p "$BIN"
echo "== extracting tools to $BIN =="
sed -n '/^__DARK_PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | tar -xzf - -C "$BIN"
chmod 755 "$BIN"/*
echo "== context + red->blue on the ACTIVE themes only =="
"$BIN/gunmetal-blue-accent" current
echo "== rebuilding Tiger-Gunmetal v3 (dark) =="
"$BIN/tiger-gunmetal-emerald-theme" build --force
"$BIN/tiger-gunmetal-gtk3-theme" build --force
echo "== restarting emerald =="
if command -v emerald >/dev/null 2>&1; then (emerald --replace >/dev/null 2>&1 &); echo "  emerald --replace sent"; else echo "  emerald not found; restart manually"; fi
echo "== previews (send photos of these / the live desktop) =="
ls -l "$HOME/.emerald/themes/Tiger-Gunmetal-Aqua/theme.screenshot.png" "$HOME/.themes/Tiger-Gunmetal-3D/gtk-3.0/tiger3d/preview.png"
echo "To try the v3 deco: tiger-gunmetal-emerald-theme apply && tiger-gunmetal-gtk3-theme apply"
echo "To go back:        tiger-gunmetal-gtk3-theme restore && tiger-gunmetal-emerald-theme restore --baseline $HOME/.emerald/themes/Quake-Gunmetal-Aqua"
exit 0
