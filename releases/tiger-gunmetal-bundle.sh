#!/bin/sh
# tiger-gunmetal-bundle.sh — one-file installer for the Tiger-Gunmetal theme pair
# (OS X 10.4 brushed gunmetal + Prussian blue). Run on the Void desktop as user sd:
#   sh tiger-gunmetal-bundle.sh          installs tools, builds both themes, probes GTK
# Then apply when you like the previews:
#   tiger-gunmetal-emerald-theme apply && tiger-gunmetal-gtk3-theme apply
# Rollback:
#   tiger-gunmetal-gtk3-theme restore && tiger-gunmetal-emerald-theme restore
set -e
BIN="$HOME/.local/bin"
EMERALD_SOURCE="${TIGER_EMERALD_SOURCE:-/usr/share/emerald/themes/Mac4Lin_Aqua}"
GTK_SOURCE="${TIGER_GTK_SOURCE:-$HOME/.themes/Quake-Gunmetal-3D}"
mkdir -p "$BIN"
echo "== extracting tools to $BIN =="
sed -n '/^__TIGER_PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | tar -xzf - -C "$BIN"
chmod 755 "$BIN/gunmetal-emerald-theme" "$BIN/gunmetal-gtk3-theme" "$BIN/tiger-gunmetal-emerald-theme" "$BIN/tiger-gunmetal-gtk3-theme"
echo "== building Emerald deco (from $EMERALD_SOURCE) =="
"$BIN/tiger-gunmetal-emerald-theme" build --source "$EMERALD_SOURCE"
echo "== building GTK3 theme (from $GTK_SOURCE) =="
"$BIN/tiger-gunmetal-gtk3-theme" build --source "$GTK_SOURCE"
echo "== GTK realization probe =="
"$BIN/tiger-gunmetal-gtk3-theme" probe || echo "PROBE SKIPPED (no GTK session right now)"
echo "== previews (screenshot these and send back) =="
ls -l "$HOME/.emerald/themes/Tiger-Gunmetal-Aqua/theme.screenshot.png" "$HOME/.themes/Tiger-Gunmetal-3D/gtk-3.0/tiger3d/preview.png"
echo "INSTALL OK"
exit 0
